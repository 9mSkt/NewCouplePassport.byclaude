// Generates supabase/migrations/002_countries.sql from src/lib/countries.ts (single source of truth).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'src/lib/countries.ts'), 'utf8');
const block = src.slice(src.indexOf('CONTINENT_COUNTRIES'), src.indexOf('};'));
const rows = [];
for (const m of block.matchAll(/\b(AF|AN|AS|EU|NA|OC|SA):\s*'([A-Z ]+)'/g)) {
  for (const code of m[2].trim().split(/\s+/)) rows.push(`('${code}','${m[1]}')`);
}
if (rows.length < 240) throw new Error(`only parsed ${rows.length} countries`);

const sql = `-- Generated by scripts/gen-countries-sql.mjs — do not edit by hand.
insert into public.countries (code, continent) values
${rows.join(',\n')}
on conflict (code) do update set continent = excluded.continent;
`;
writeFileSync(join(root, 'supabase/migrations/002_countries.sql'), sql);
console.log(`wrote ${rows.length} countries`);
